function typeName(t: string): string {
  const map: Record<string, string> = {
    string: 'metin',
    number: 'sayı',
    integer: 'tam sayı',
    boolean: 'doğru/yanlış',
    array: 'liste',
    object: 'nesne',
    null: 'boş (null)',
  };
  return t
    .split(',')
    .map((x) => map[x.trim()] ?? x)
    .join(' veya ');
}
